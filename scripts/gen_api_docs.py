#!/usr/bin/env python3
"""Regenerate docs/api.md and the SDK's OpenAPI snapshot from the app itself.

Run with the backend's environment. --check fails if either file is out of date.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("SPAIDER_INSECURE_DEV", "true")
SNAPSHOT = ROOT / "sdk/python/contract/openapi.json"
API_DOC = ROOT / "docs/api.md"
_METHODS = ("get", "post", "put", "patch", "delete")


def render(spec: dict) -> str:
    lines = [
        "# REST API",
        "",
        "Generated by `scripts/gen_api_docs.py`. Do not edit by hand.",
        "",
        "Every route except `/health` and `/api/v1/auth/bootstrap` needs an API key,",
        "sent as `X-Api-Key` or `Authorization: Bearer`.",
    ]
    groups: dict[str, list[tuple[str, str, str]]] = {}
    for path, operations in sorted(spec["paths"].items()):
        for method in _METHODS:
            if method in operations:
                operation = operations[method]
                tag = (operation.get("tags") or ["other"])[0]
                summary = " ".join((operation.get("summary") or "").split())
                groups.setdefault(tag, []).append((method.upper(), path, summary))
    for tag in sorted(groups):
        lines += ["", f"## {tag}", "", "| Method | Path | Summary |", "| --- | --- | --- |"]
        lines += [f"| {method} | `{path}` | {summary} |" for method, path, summary in groups[tag]]
    return "\n".join(lines) + "\n"


def main() -> int:
    from app.main import app

    spec = app.openapi()
    snapshot, doc = json.dumps(spec, indent=2, sort_keys=True) + "\n", render(spec)
    if "--check" in sys.argv:
        stale = [
            str(path.relative_to(ROOT))
            for path, content in ((SNAPSHOT, snapshot), (API_DOC, doc))
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        if stale:
            print(f"Out of date: {', '.join(stale)}. Run scripts/gen_api_docs.py.", file=sys.stderr)
            return 1
        return 0
    SNAPSHOT.write_text(snapshot, encoding="utf-8")
    API_DOC.write_text(doc, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
